/**
 * Pre-build script: reads all .vue example files and generates
 * src/examples/raw-sources.generated.js with raw source code strings.
 */
const fs = require('fs')
const path = require('path')

const examplesDir = path.resolve(__dirname, '../src/examples')
const outputFile = path.resolve(__dirname, '../src/examples/raw-sources.generated.js')

// Walk subdirectories and collect .vue files.
//
// 结果**必须排序**：`readdirSync` 的顺序由文件系统决定（NTFS 大致有序、ext4 是哈希序），
// 不排就同一份源码在不同机器/检出上产出不同字节的生成物 —— 这个文件的定位是「提交进库的
// 派生物」，顺序不稳就等于每次换环境都产生一次无意义的 diff。当前 88 个键在 Windows 上
// 恰好已是有序的，所以补上 sort() 对本机产物逐字节无变化，只是把「恰好」变成「保证」。
function walk(dir, base) {
  const results = []
  const entries = fs.readdirSync(dir, { withFileTypes: true })
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      results.push(...walk(fullPath, base))
    } else if (entry.name.endsWith('.vue')) {
      const relative = path.relative(base, fullPath).replace(/\\/g, '/')
      const key = relative.replace(/\.vue$/, '')
      const content = fs.readFileSync(fullPath, 'utf-8')
      results.push({ key, content })
    }
  }
  return results
}

const sources = walk(examplesDir, examplesDir).sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0))

// Generate the JS module — each source as a named export
// 刻意**不写生成时间**：带时间戳会让本文件在每次 prebuild/preserve 后都与库里那份不同，
// 工作树因此常态变脏（改动本身零信息量，却混进每次 `git status`，也让人不敢确认
// 「生成物是否真的与源码同步」）。生成物的可验证性来自「内容由源码唯一决定」，
// 而不是「什么时候生成的」。
let output = '// AUTO-GENERATED — DO NOT EDIT\n'
output += '// Generated by scripts/generate-raw-sources.js\n\n'

for (const { key, content } of sources) {
  // Escape backticks, dollar signs, and backslashes for template literal
  const escaped = content
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$/g, '\\$')
  output += `export const RAW_${key.replace(/[/-]/g, '_')} = \`${escaped}\`\n`
}

// Also export a lookup map
output += '\n// Lookup map: category/key → raw source string\n'
output += 'export const RAW_SOURCES = {\n'
for (const { key } of sources) {
  const varName = `RAW_${key.replace(/[/-]/g, '_')}`
  output += `  '${key}': ${varName},\n`
}
output += '}\n'

fs.writeFileSync(outputFile, output)
console.log(`Generated raw sources for ${sources.length} files → ${outputFile}`)
